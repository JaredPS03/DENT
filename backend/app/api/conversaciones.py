"""/api/conversaciones: a person of the clinic takes a chat, writes in it and gives it back to the bot.

The clinic comes from the session; a conversation id only counts if RLS finds it in that clinic.
Messages are queued and the worker sends them in order with the bot's own rules (window,
allowed numbers, at most once). Every action leaves its audit_log row, never the message text.
"""

from datetime import datetime, timedelta
from typing import Literal
from uuid import UUID

from fastapi import APIRouter, HTTPException, Request, status
from fastapi.responses import JSONResponse
from psycopg import AsyncConnection
from pydantic import BaseModel, ConfigDict, Field

from app.api.auth import PanelSession
from app.api.session import SessionDep
from app.db import conversations as db
from app.dependencies import get_db
from app.jobs.queue import ConversationJob, ExpireHoldJob, enqueue
from app.whatsapp import outbound
from app.whatsapp.outbound import MAX_TEXT, InvalidOutboundError
from app.whatsapp.window import window_is_open

router = APIRouter(prefix="/api/conversaciones", tags=["conversaciones"])

# Asks the patient to come back once the 24 h window closed (spec, WhatsApp templates).
REOPEN_TEMPLATE = "retomar_conversacion"
# Used as {{1}} when the patient never told their name: "Hola de nuevo, te escribimos de…".
UNKNOWN_NAME_GREETING = "de nuevo"
# The hold expires a little after 24 h, so the database's clock always agrees it is due.
HOLD_EXPIRY_DELAY = db.HOLD_TTL + timedelta(minutes=1)


class _Strict(BaseModel):
    model_config = ConfigDict(extra="forbid")


class NewMessage(_Strict):
    text: str = Field(min_length=1, max_length=MAX_TEXT)
    # Generated by the panel for each message: a double tap or a retried request sends it once.
    client_message_id: UUID


class ConversationOut(BaseModel):
    id: UUID
    status: str
    window_expires_at: datetime | None
    bot_paused_until: datetime | None


class QueuedMessageOut(BaseModel):
    id: UUID
    # 'pending': goes out now. 'held': the 24 h window closed; it goes out when the patient
    # answers retomar_conversacion, or is marked as not sent after 24 h.
    status: str
    reopen_requested: bool


@router.post("/{conversation_id}/tomar", response_model=ConversationOut)
async def take(conversation_id: UUID, session: SessionDep, request: Request) -> ConversationOut:
    """A person takes the chat: the bot stops answering in it until someone gives it back."""
    async with get_db(request).clinic_transaction(session.clinic_id) as conn:
        conversation = await _locked(conn, conversation_id)
        if conversation.status != "human":
            await _set_status(conn, session, conversation, "human")
        return _out(await _locked(conn, conversation_id))


@router.post("/{conversation_id}/soltar", response_model=ConversationOut)
async def release(conversation_id: UUID, session: SessionDep, request: Request) -> ConversationOut:
    """Gives the chat back to the bot, also ending a pause from a reply sent with the clinic's app."""
    async with get_db(request).clinic_transaction(session.clinic_id) as conn:
        conversation = await _locked(conn, conversation_id)
        if conversation.status != "bot" or conversation.bot_paused_until is not None:
            await _set_status(conn, session, conversation, "bot")
        return _out(await _locked(conn, conversation_id))


@router.post(
    "/{conversation_id}/mensajes", status_code=status.HTTP_202_ACCEPTED, response_model=QueuedMessageOut
)
async def send_message(
    conversation_id: UUID, body: NewMessage, session: SessionDep, request: Request
) -> QueuedMessageOut | JSONResponse:
    try:
        payload = outbound.text(body.text)
    except InvalidOutboundError as invalid:
        return JSONResponse({"detail": str(invalid)}, status_code=status.HTTP_422_UNPROCESSABLE_CONTENT)

    async with get_db(request).clinic_transaction(session.clinic_id) as conn:
        conversation = await _locked(conn, conversation_id)
        # Writing in the chat takes it: the bot and a person never answer at the same time.
        if conversation.status != "human":
            await _set_status(conn, session, conversation, "human")

        now = await db.database_now(conn)
        window_open = window_is_open(conversation.window_expires_at, now)
        template = None if window_open else await db.approved_template(conn, REOPEN_TEMPLATE)
        if not window_open and template is None:
            raise HTTPException(
                status.HTTP_409_CONFLICT,
                "Pasaron más de 24 horas desde el último mensaje del paciente y la plantilla "
                "retomar_conversacion todavía no está aprobada por Meta.",
            )

        message = await db.insert_outbound(
            conn,
            clinic_id=session.clinic_id,
            conversation_id=conversation_id,
            sender="human",
            message_type="text",
            content=body.text,
            send_payload=payload,
            billing_category="service",
            delivery_status="pending" if window_open else "held",
            idempotency_key=f"panel:{body.client_message_id}",
        )
        if not message.created:
            # The same message again (double tap, retried request): nothing new is sent.
            return QueuedMessageOut(
                id=message.id, status=message.delivery_status or "pending", reopen_requested=False
            )

        reopen_requested = False
        if template is not None:
            reopen_requested = await _ask_patient_to_come_back(conn, session, conversation_id, template, body)
            await enqueue(
                conn,
                ExpireHoldJob(clinic_id=session.clinic_id, message_id=message.id),
                delay_seconds=int(HOLD_EXPIRY_DELAY.total_seconds()),
            )
        await enqueue(conn, ConversationJob(clinic_id=session.clinic_id, conversation_id=conversation_id))
        await db.insert_audit(
            conn,
            clinic_id=session.clinic_id,
            user_id=session.user_id,
            action="message.send",
            table_name="messages",
            record_id=message.id,
            changes={
                "conversation_id": str(conversation_id),
                "held": not window_open,
                "reopen_requested": reopen_requested,
            },
        )
        return QueuedMessageOut(
            id=message.id, status="pending" if window_open else "held", reopen_requested=reopen_requested
        )


async def _ask_patient_to_come_back(
    conn: AsyncConnection,
    session: PanelSession,
    conversation_id: UUID,
    template: db.ApprovedTemplate,
    body: NewMessage,
) -> bool:
    """Queues retomar_conversacion, unless one already went out since the patient's last message."""
    if await db.reopen_request_pending(conn, conversation_id, REOPEN_TEMPLATE):
        return False
    patient_name, clinic_name = await db.patient_and_clinic_names(conn, conversation_id)
    first_name = patient_name.split()[0] if patient_name and patient_name.strip() else UNKNOWN_NAME_GREETING
    # Meta rejects template parameters with line breaks, tabs or runs of spaces.
    clinic_name = " ".join(clinic_name.split())
    await db.insert_outbound(
        conn,
        clinic_id=session.clinic_id,
        conversation_id=conversation_id,
        sender="system",
        message_type="template",
        content=REOPEN_TEMPLATE,
        send_payload=outbound.template(template.name, template.language, [first_name, clinic_name]),
        billing_category=template.category,
        delivery_status="pending",
        idempotency_key=f"reopen:{body.client_message_id}",
    )
    return True


async def _locked(conn: AsyncConnection, conversation_id: UUID) -> db.Conversation:
    conversation = await db.conversation_for_update(conn, conversation_id)
    if conversation is None:
        raise HTTPException(status.HTTP_404_NOT_FOUND, "No encontramos esa conversación.")
    return conversation


async def _set_status(
    conn: AsyncConnection,
    session: PanelSession,
    conversation: db.Conversation,
    new_status: Literal["bot", "human"],
) -> None:
    await db.set_status(conn, conversation.id, new_status)
    await db.insert_audit(
        conn,
        clinic_id=session.clinic_id,
        user_id=session.user_id,
        action="conversation.take" if new_status == "human" else "conversation.release",
        table_name="conversations",
        record_id=conversation.id,
        changes={"status": [conversation.status, new_status]},
    )


def _out(conversation: db.Conversation) -> ConversationOut:
    return ConversationOut(
        id=conversation.id,
        status=conversation.status,
        window_expires_at=conversation.window_expires_at,
        bot_paused_until=conversation.bot_paused_until,
    )
